//! The Django bridge on all three databases: tables shaped exactly as Django's schema editor
//! makes them, a real Django password hash, then the admin, the API and MCP on top.
#![cfg(all(feature = "admin", feature = "sqlite"))]

use axum::body::{to_bytes, Body};
use axum::http::{header, Request, StatusCode};
use rangoli::orm::{Dialect, FieldType};
use rangoli::Model;
use tower::ServiceExt;

/// Django 6.1.2: make_password("django-pass", salt="rangoli", iterations=1000).
const HASH: &str = "pbkdf2_sha256$1000$rangoli$b25uwZU5YUpcAgAuLYZqh/twCO6//0gD0l9udxTs7zw=";

/// The DDL Django's schema editor emits for these models on each database.
fn ddl(d: Dialect) -> Vec<String> {
    let (pk, boolean, decimal, stamp, fk) = match d {
        Dialect::Postgres => {
            ("bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "boolean", "numeric(10, 2)", "timestamp with time zone", "bigint")
        }
        Dialect::Mysql => ("bigint AUTO_INCREMENT NOT NULL PRIMARY KEY", "bool", "numeric(10, 2)", "datetime(6)", "bigint"),
        Dialect::Sqlite => ("integer NOT NULL PRIMARY KEY AUTOINCREMENT", "bool", "decimal", "datetime", "bigint"),
    };
    let q = |s: &str| d.quote(s);
    vec![
        format!(
            "CREATE TABLE {} ({} {pk}, {} varchar(128) NOT NULL, {} varchar(150) NOT NULL UNIQUE, {} {boolean} NOT NULL, {} {boolean} NOT NULL, {} {boolean} NOT NULL)",
            q("auth_user"), q("id"), q("password"), q("username"), q("is_staff"), q("is_superuser"), q("is_active")
        ),
        format!("CREATE TABLE {} ({} {pk}, {} varchar(100) NOT NULL)", q("shop_customer"), q("id"), q("name")),
        format!(
            // A table-level constraint: MySQL silently ignores REFERENCES written on the column.
            "CREATE TABLE {} ({} {pk}, {} varchar(20) NOT NULL, {} {boolean} NOT NULL, {} {decimal} NOT NULL, {} {stamp} NOT NULL, {} varchar(64) NOT NULL, {} {fk} NULL, FOREIGN KEY ({}) REFERENCES {} ({}))",
            q("shop_order"), q("id"), q("code"), q("paid"), q("total"), q("placed_at"), q("api_key"), q("customer_id"), q("customer_id"), q("shop_customer"), q("id")
        ),
        format!("CREATE TABLE {} ({} varchar(40) NOT NULL PRIMARY KEY, {} text NOT NULL)", q("django_session"), q("session_key"), q("session_data")),
        format!("INSERT INTO {} ({}, {}, {}, {}, {}) VALUES ('{HASH}', 'ada', TRUE, FALSE, TRUE)", q("auth_user"), q("password"), q("username"), q("is_staff"), q("is_superuser"), q("is_active")),
        format!("INSERT INTO {} ({}) VALUES ('Acme')", q("shop_customer"), q("name")),
        format!(
            "INSERT INTO {} ({}, {}, {}, {}, {}, {}) VALUES ('A-1', TRUE, 19.99, '2026-10-14 09:30:00', 'sk_live_hidden', 1)",
            q("shop_order"), q("code"), q("paid"), q("total"), q("placed_at"), q("api_key"), q("customer_id")
        ),
    ]
}

#[tokio::test]
async fn django_database_to_admin_api_and_mcp() {
    let url = std::env::var("RANGOLI_TEST_DATABASE_URL").ok().filter(|u| !u.is_empty()).unwrap_or_else(|| {
        let p = std::env::temp_dir().join(format!("rangoli-django-{}.sqlite3", std::process::id()));
        let _ = std::fs::remove_file(&p);
        format!("sqlite://{}?mode=rwc", p.display())
    });
    std::env::set_var("RANGOLI_DATABASE_URL", &url);
    let db = rangoli::orm::connect(&url).await.unwrap();
    for t in [
        "shop_order",
        "shop_customer",
        "django_session",
        "rangoli_setting",
        "rangoli_event",
        "rangoli_user_groups",
        "rangoli_group",
        "rangoli_password_reset",
        "rangoli_oauth_code",
        "rangoli_oauth_client",
        "rangoli_webhook",
        "rangoli_pending_change",
        "rangoli_api_token",
        "rangoli_login_failure",
        "rangoli_session",
        "rangoli_admin_log",
        "rangoli_task",
        "e2e_note",
        "rangoli_user",
        "auth_user",
        "rangoli_migrations",
    ] {
        sqlx::query(&format!("DROP TABLE IF EXISTS {}", db.dialect.quote(t))).execute(&db.pool).await.unwrap();
    }
    for sql in ddl(db.dialect) {
        sqlx::query(&sql).execute(&db.pool).await.unwrap_or_else(|e| panic!("{sql}: {e}"));
    }

    let schema = rangoli::django::introspect().await.unwrap();
    let tables: Vec<&str> = schema.models.iter().map(|m| m.table).collect();
    assert!(tables.contains(&"shop_customer") && tables.contains(&"shop_order"), "{tables:?}");
    assert!(
        !tables.iter().any(|t| t.starts_with("auth_") || t.starts_with("django_") || t.starts_with("rangoli_")),
        "Django's own tables are left out: {tables:?}"
    );
    let order = schema.models.iter().find(|m| m.table == "shop_order").unwrap();
    let ty = |n: &str| order.field(n).unwrap().ty;
    assert_eq!(
        (ty("paid"), ty("total"), ty("placed_at"), ty("code")),
        (FieldType::Bool, FieldType::Opaque, FieldType::Opaque, FieldType::Varchar(20))
    );
    assert!(order.field("api_key").unwrap().private, "sensitive-looking columns are private");
    assert_eq!(order.field("customer_id").unwrap().fk, Some("shop_customer"), "foreign keys are found");

    let app = rangoli::django::app().await.unwrap().router();
    let send = |req: Request<Body>| {
        let app = app.clone();
        async move {
            let res = app.oneshot(req).await.unwrap();
            let (status, headers) = (res.status(), res.headers().clone());
            (status, headers, String::from_utf8(to_bytes(res.into_body(), usize::MAX).await.unwrap().to_vec()).unwrap())
        }
    };
    let login = |pw: &str| {
        Request::post("/admin/login")
            .header(header::CONTENT_TYPE, "application/x-www-form-urlencoded")
            .header("sec-fetch-site", "same-origin")
            .body(Body::from(format!("username=ada&password={pw}")))
            .unwrap()
    };
    assert_eq!(send(login("wrong")).await.0, StatusCode::UNAUTHORIZED);
    let (status, headers, _) = send(login("django-pass")).await;
    assert_eq!(status, StatusCode::SEE_OTHER, "a Django staff account signs in with its Django password");
    let cookie = headers[header::SET_COOKIE].to_str().unwrap().split(';').next().unwrap().to_string();
    let page = |uri: &str| Request::get(uri).header(header::COOKIE, &cookie).body(Body::empty()).unwrap();
    let (status, _, body) = send(page("/admin/shop_order/")).await;
    assert!(status == StatusCode::OK && body.contains("A-1"), "the admin lists Django's rows: {status} {}", &body[..body.len().min(400)]);
    let (_, _, body) = send(page("/api/shop_order/")).await;
    let list: serde_json::Value = serde_json::from_str(&body).unwrap();
    let row = &list["results"][0];
    assert_eq!((row["code"].as_str(), row["paid"].as_bool()), (Some("A-1"), Some(true)), "{body}");
    assert!(row["total"].as_str().unwrap().starts_with("19.99"), "numeric shown as text: {row}");
    assert!(row["placed_at"].as_str().unwrap().starts_with("2026-10-14"), "timestamps shown as text: {row}");
    assert!(row.get("api_key").is_none() && !body.contains("sk_live_hidden"), "the secret never leaves");
    let (status, _, _) = send(
        Request::post("/api/shop_order/")
            .header(header::COOKIE, &cookie)
            .header(header::CONTENT_TYPE, "application/json")
            .header("sec-fetch-site", "same-origin")
            .body(Body::from(r#"{"code": "B-2"}"#))
            .unwrap(),
    )
    .await;
    assert_eq!(status, StatusCode::METHOD_NOT_ALLOWED, "read-only unless RANGOLI_DJANGO_WRITES=1");
    let ada = rangoli::auth::User::objects().filter(rangoli::auth::User::USERNAME.eq("ada")).get().await.unwrap();
    let (_, token) = rangoli::auth::create_token(&ada, "agent", None).await.unwrap();
    let rpc = r#"{"jsonrpc": "2.0", "id": 1, "method": "tools/list"}"#;
    let (_, _, body) = send(
        Request::post("/mcp")
            .header(header::AUTHORIZATION, format!("Bearer {token}"))
            .header(header::CONTENT_TYPE, "application/json")
            .body(Body::from(rpc))
            .unwrap(),
    )
    .await;
    let tools: serde_json::Value = serde_json::from_str(&body).unwrap();
    let names: Vec<&str> = tools["result"]["tools"].as_array().unwrap().iter().map(|t| t["name"].as_str().unwrap()).collect();
    assert!(names.contains(&"shop_order_list") && !names.iter().any(|n| n.ends_with("_create")), "agents get read tools: {names:?}");
    assert!(!body.contains("api_key"), "and never learn the secret column exists");
}
